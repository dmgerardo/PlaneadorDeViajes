// SVG inline de un icono Lucide. tamano en px. claseExtra se agrega a la
// clase "icono" (ej. "icono-texto" cuando va antes de una etiqueta de texto,
// para separarlo con margen — ver .icono-texto en estilos.css).
function icono(nombre, tamano, claseExtra) {
  const contenido = ICONOS_LUCIDE[nombre];
  if (!contenido) return "";
  const clase = "icono" + (claseExtra ? ` ${claseExtra}` : "");
  return `<svg class="${clase}" width="${tamano || 16}" height="${tamano || 16}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${contenido}</svg>`;
}

// Icono + texto separados por el margen de .icono-texto — el atajo más común.
function iconoTexto(nombre, texto, tamano) {
  return `${icono(nombre, tamano, "icono-texto")}${esc(texto)}`;
}
